CREATE TABLE categorias (
    id      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre  VARCHAR(50) UNIQUE NOT NULL,
    color   CHAR(7) NOT NULL
);
CREATE TABLE usuarios (
    id        INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    email     VARCHAR(150) unique NOT NULL,
    password  VARCHAR(255) NOT NULL,
    perfil    TINYINT(1)   NOT NULL DEFAULT 0,
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN (0, 1))
);
CREATE TABLE articulos (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    titulo        VARCHAR(200) NOT NULL,
    contenido     TEXT         NOT NULL,
    publicado     ENUM('Si', 'No') NOT NULL DEFAULT 'No',
    imagen        VARCHAR(255) NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    categoria_id  INT UNSIGNED NOT NULL,
    usuario_id    INT UNSIGNED NOT NULL,
    CONSTRAINT fk_articulos_categoria FOREIGN KEY (categoria_id)
        REFERENCES categorias(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_articulos_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id) ON DELETE CASCADE ON UPDATE CASCADE
);

